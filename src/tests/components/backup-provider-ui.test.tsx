import React from 'react';
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen } from '@testing-library/react';
import { axe, toHaveNoViolations } from 'jest-axe';
import { WorkspaceHeader } from '@/components/workspace/workspace-header';
import { PlanProvider } from '@/components/plan-context';
import { AuthProvider } from '@/components/auth-context';
import { SAVED_EXAMPLES } from '@/data/savedExamples';
import { EventPlan } from '@/lib/schemas';
import { BACKUP_PROVIDER_EXPIRED_NOTICE, MAIN_PROVIDER_EXPIRED_NOTICE } from '@/lib/ai/groq-provider';
import fireEvent from '@testing-library/user-event';

expect.extend(toHaveNoViolations);

// Mock child modal
vi.mock('@/components/workspace/print-modal', () => ({
  PrintModal: () => <div data-testid="mock-print-modal" />,
}));

function renderWithProviders(ui: React.ReactElement, plan: EventPlan) {
  return render(
    <AuthProvider>
      <PlanProvider initialPlan={plan}>
        {ui}
      </PlanProvider>
    </AuthProvider>
  );
}

describe('Non-Primary Plan UI Indicators & "Try again with AI" Flow', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('renders "Generated by a backup AI provider" banner and badge with text and icon', () => {
    const backupPlan: EventPlan = {
      ...SAVED_EXAMPLES.wedding,
      generationSource: 'backup',
    };

    renderWithProviders(<WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />, backupPlan);

    // Verify badge in metadata row
    expect(screen.getByText('Backup AI')).toBeDefined();

    // Verify prominent banner
    expect(screen.getByText('Generated by a backup AI provider')).toBeDefined();
    expect(
      screen.getByText(/Primary AI experienced high traffic; this draft was generated via our backup AI provider/i)
    ).toBeDefined();

    // Verify accessible "Try again with AI" button
    const retryBtn = screen.getByRole('button', { name: /Try again with AI/i });
    expect(retryBtn).toBeDefined();
    expect(retryBtn.tagName).toBe('BUTTON');
  });

  it('renders "Built-in template plan (AI is busy)" banner and badge with text and icon', () => {
    const templatePlan: EventPlan = {
      ...SAVED_EXAMPLES.wedding,
      generationSource: 'template',
    };

    renderWithProviders(<WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />, templatePlan);

    // Verify badge in metadata row
    expect(screen.getByText('Built-in Template')).toBeDefined();

    // Verify prominent banner
    expect(screen.getByText('Built-in template plan (AI is busy)')).toBeDefined();
    expect(
      screen.getByText(/Generated immediately by our deterministic offline planner/i)
    ).toBeDefined();

    // Verify accessible "Try again with AI" button
    const retryBtn = screen.getByRole('button', { name: /Try again with AI/i });
    expect(retryBtn).toBeDefined();
  });

  it('does NOT render backup/template banner when plan is generated by primary AI', () => {
    const primaryPlan: EventPlan = {
      ...SAVED_EXAMPLES.wedding,
      generationSource: 'primary',
    };

    renderWithProviders(<WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />, primaryPlan);

    expect(screen.queryByText('Generated by a backup AI provider')).toBeNull();
    expect(screen.queryByText('Built-in template plan (AI is busy)')).toBeNull();
    expect(screen.queryByText('Backup AI')).toBeNull();
    expect(screen.queryByText('Built-in Template')).toBeNull();
  });

  it('renders calm, dismissible provider notice when backup demo key is inactive', async () => {
    const user = fireEvent.setup();
    const noticePlan: EventPlan = {
      ...SAVED_EXAMPLES.wedding,
      generationSource: 'template',
      providerNotice: BACKUP_PROVIDER_EXPIRED_NOTICE,
    };

    renderWithProviders(<WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />, noticePlan);

    // Notice must render with role="status"
    const noticeEl = screen.getByTestId('provider-notice');
    expect(noticeEl).toBeDefined();
    expect(noticeEl.getAttribute('role')).toBe('status');
    expect(screen.getByText('Provider Availability Notice')).toBeDefined();
    expect(screen.getByText(BACKUP_PROVIDER_EXPIRED_NOTICE)).toBeDefined();

    // Notice is dismissible
    const dismissBtn = screen.getByRole('button', { name: /Dismiss provider notice/i });
    expect(dismissBtn).toBeDefined();
    await user.click(dismissBtn);

    // Notice should disappear after clicking dismiss
    expect(screen.queryByText(BACKUP_PROVIDER_EXPIRED_NOTICE)).toBeNull();
  });

  it('renders equivalent calm notice for main AI provider when main key is invalid or expired', () => {
    const mainNoticePlan: EventPlan = {
      ...SAVED_EXAMPLES.wedding,
      generationSource: 'template',
      providerNotice: MAIN_PROVIDER_EXPIRED_NOTICE,
    };

    renderWithProviders(<WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />, mainNoticePlan);
    expect(screen.getByText(MAIN_PROVIDER_EXPIRED_NOTICE)).toBeDefined();
  });

  it('does NOT render provider notice when plan was created by primary AI normally', () => {
    const primaryPlan: EventPlan = {
      ...SAVED_EXAMPLES.wedding,
      generationSource: 'primary',
      providerNotice: undefined,
    };

    renderWithProviders(<WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />, primaryPlan);
    expect(screen.queryByTestId('provider-notice')).toBeNull();
    expect(screen.queryByText(/The backup AI provider is no longer active/i)).toBeNull();
    expect(screen.queryByText(/The main AI provider is no longer active/i)).toBeNull();
  });

  describe('Accessibility (jest-axe) Checks for Non-Primary UI States', () => {
    it('has no accessibility violations for Backup AI state (Light theme)', async () => {
      const backupPlan: EventPlan = {
        ...SAVED_EXAMPLES.wedding,
        generationSource: 'backup',
      };

      const { container } = renderWithProviders(
        <WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />,
        backupPlan
      );

      const results = await axe(container);
      expect(results).toHaveNoViolations();
    });

    it('has no accessibility violations for Built-in Template state (Dark theme)', async () => {
      const templatePlan: EventPlan = {
        ...SAVED_EXAMPLES.wedding,
        generationSource: 'template',
      };

      const { container } = render(
        <div className="dark bg-neutral-900 text-neutral-100">
          <AuthProvider>
            <PlanProvider initialPlan={templatePlan}>
              <WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />
            </PlanProvider>
          </AuthProvider>
        </div>
      );

      const results = await axe(container);
      expect(results).toHaveNoViolations();
    });

    it('has no accessibility violations when provider notice is displayed', async () => {
      const noticePlan: EventPlan = {
        ...SAVED_EXAMPLES.wedding,
        generationSource: 'template',
        providerNotice: BACKUP_PROVIDER_EXPIRED_NOTICE,
      };

      const { container } = renderWithProviders(
        <WorkspaceHeader onOpenReplan={vi.fn()} activeTabName="Overview" />,
        noticePlan
      );

      const results = await axe(container);
      expect(results).toHaveNoViolations();
    });
  });
});
